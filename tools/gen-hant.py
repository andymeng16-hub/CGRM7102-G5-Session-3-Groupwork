#!/usr/bin/env python3
"""Generate data/zh-hant.js, the Simplified to Traditional (Hong Kong) table.

The site keeps one Chinese source of truth: Simplified. The Traditional
version is derived from it at run time, so the two languages can never drift
apart. This script crops the zhconv table down to the characters the site
actually uses, then writes a compact dictionary plus a longest-prefix
converter that behaves exactly like zhconv.convert(text, 'zh-hk').

    python3 tools/gen-hant.py            write data/zh-hant.js
    python3 tools/gen-hant.py --check    verify the table against zhconv

Re-run it after adding or editing Simplified Chinese anywhere in the site.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

try:
    import zhconv
except ImportError:
    sys.exit('zhconv is required: pip3 install zhconv')

# Sources scanned for Chinese characters. The generated file is excluded so it
# never feeds back into its own character set.
SCAN = [
    'index.html',
    'app.js',
    'data/field-data.js',
    'data/vegetation.js',
    'data/terrain.js',
]

# Hong Kong convention. zhconv already returns Hong Kong forms for most of
# these, but a few characters and phrases come out as a variant or a form that
# reads wrong in a Hong Kong field guide, so they are corrected by hand.
OVERRIDES = {
    # Characters: the table prefers a variant, or a form that is wrong here.
    '说': '說',       # zhconv gives the Japanese variant 説
    '岩': '岩',       # Hong Kong writes 岩石, zhconv prefers 巖石
    '群': '群',       # zhconv gives the old variant 羣
    '干': '干',       # 干扰 must not become 幹擾
    '峰': '峰',       # zhconv gives the variant 峯
    '启': '啟',       # zhconv gives 啓
    '托': '托',       # 托出水面 must not become 託
    '叙': '敘',       # zhconv gives the variant 敍
    '悦': '悅',       # the zh-hk table maps 悅 back to 悦
    # Words: a phrase the table would otherwise mangle.
    '公里': '公里',    # zh-hk gives 公裏
    '县志': '縣志',
    '路径': '路徑',
    '径行': '徑行',    # zh-hk reads 路径行走 as 徑行 and writes 逕
    '游标': '游標',
    '观景台': '觀景台',  # Hong Kong writes 觀景台, not 觀景臺
    '说明': '說明',
    '岩石': '岩石',
}

CJK = re.compile(r'[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]')


def used_characters():
    """Every Chinese character that appears in the site sources."""
    chars = set()
    for rel in SCAN:
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            continue
        with open(path, encoding='utf-8') as fh:
            chars.update(CJK.findall(fh.read()))
    return chars


def build_dict(chars):
    """Cropped zh-hk table plus the manual overrides."""
    zhcdicts = zhconv.zhconv.zhcdicts
    if zhcdicts is None:
        zhconv.zhconv.loaddict()
    zhcdicts = zhconv.zhconv.zhcdicts

    table = dict(zhcdicts['zh2Hant'])
    table.update(zhcdicts['zh2HK'])

    cropped = {}
    for key, val in table.items():
        if '|' in val:          # ambiguous variants, zhconv picks one at random
            continue
        if not all(ch in chars for ch in key):
            continue
        cropped[key] = val
    cropped.update(OVERRIDES)
    return cropped


def longest_key_length(table):
    return max((len(k) for k in table), default=1)


def write_js(table, out_path):
    maxlen = longest_key_length(table)
    payload = json.dumps(table, ensure_ascii=False, sort_keys=True,
                         separators=(',', ':'))
    js = """/* Simplified to Traditional (Hong Kong) conversion table.
   Generated by tools/gen-hant.py. Do not edit by hand.
   The site keeps Simplified Chinese as the single source of truth and derives
   the Traditional version at run time through toHant(). */
(function (root) {
  'use strict';
  var DICT = %s;
  var MAXLEN = %d;

  /* Longest prefix match, the same rule zhconv uses, so a phrase such as
     里面 is read as a word before the characters inside it are looked at. */
  function toHant(str) {
    if (!str) return str;
    var out = '';
    var i = 0;
    var n = str.length;
    while (i < n) {
      var hit = null;
      var lim = n - i < MAXLEN ? n - i : MAXLEN;
      for (var len = lim; len >= 1; len--) {
        var frag = str.substr(i, len);
        if (Object.prototype.hasOwnProperty.call(DICT, frag)) {
          hit = frag;
          break;
        }
      }
      if (hit === null) {
        out += str.charAt(i);
        i += 1;
      } else {
        out += DICT[hit];
        i += hit.length;
      }
    }
    return out;
  }

  root.ZH_HANT = { dict: DICT, toHant: toHant };
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = root.ZH_HANT;
  }
})(typeof window !== 'undefined' ? window : globalThis);
""" % (payload, maxlen)
    with open(out_path, 'w', encoding='utf-8') as fh:
        fh.write(js)
    return len(payload)


def check(table):
    """Compare the cropped table against zhconv for every Chinese run."""
    runs = set()
    for rel in SCAN:
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            continue
        with open(path, encoding='utf-8') as fh:
            text = fh.read()
        for run in re.findall(r'[\\u3400-\\u4dbf\\u4e00-\\u9fff\\uf900-\\ufaff]+', text):
            runs.add(run)
    bad = []
    for run in sorted(runs):
        want = zhconv.convert(run, 'zh-hk', OVERRIDES)
        got = convert_local(run, table)
        if want != got:
            bad.append((run, want, got))
    return runs, bad


def convert_local(text, table):
    maxlen = longest_key_length(table)
    out = []
    i = 0
    n = len(text)
    while i < n:
        hit = None
        lim = n - i if n - i < maxlen else maxlen
        for length in range(lim, 0, -1):
            frag = text[i:i + length]
            if frag in table:
                hit = frag
                break
        if hit is None:
            out.append(text[i])
            i += 1
        else:
            out.append(table[hit])
            i += len(hit)
    return ''.join(out)


def main():
    chars = used_characters()
    table = build_dict(chars)
    out_path = os.path.join(ROOT, 'data', 'zh-hant.js')
    size = write_js(table, out_path)

    runs, bad = check(table)
    print('characters in site: %d' % len(chars))
    print('dictionary entries: %d' % len(table))
    print('dictionary bytes  : %d' % size)
    print('chinese runs checked: %d' % len(runs))
    if bad:
        print('MISMATCH:')
        for run, want, got in bad[:40]:
            print('  %s  expected %s  got %s' % (run, want, got))
        sys.exit(1)
    print('all runs match zhconv zh-hk output')


if __name__ == '__main__':
    main()
